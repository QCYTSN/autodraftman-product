import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const base=process.env.AUDIT_BASE_URL || 'http://127.0.0.1:5173';
const output=process.env.AUDIT_OUTPUT || '.review/editor-formula-input';
await mkdir(output,{recursive:true});
const original=await readFile('public/assets/demo/cases/diffusion/result.svg','utf8');
const title=original.match(/<text id="txt_unet_label"[\s\S]*?<\/text>/)[0];
const sample=`<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="350">${title}<text id="formula-scripts" x="775" y="170">x<tspan baseline-shift="super" font-size="10">2</tspan><tspan baseline-shift="sub" font-size="10">i</tspan> + y<tspan baseline-shift="sub" font-size="10">j</tspan></text><text id="accent" x="775" y="210">Noise ε̂<tspan baseline-shift="sub" font-size="10">θ</tspan></text></svg>`;
await writeFile(output+'/input-copy.svg',sample);
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
page.setDefaultTimeout(20000);
const checks=[],errors=[],requests=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',request=>requests.push(request.url()));
await page.addInitScript(()=>{if(!localStorage.getItem('autodraftman-language'))localStorage.setItem('autodraftman-language','zh');});
const command=(name,value)=>page.evaluate(([name,value])=>document.querySelector('iframe').contentWindow.figfoxCommand(name,value),[name,value]);
const source=()=>page.getByRole('textbox',{name:'LaTeX 源码',exact:true});
const showSource=async()=>{await page.getByRole('tab',{name:'LaTeX 源码',exact:true}).click();await source().waitFor();};
const select=async id=>{await command('select-layer',id);await page.locator('.ff-selection-summary').filter({hasText:id}).waitFor();if(!await page.locator('.ff-formula-editor').evaluate(el=>el.open))await page.locator('.ff-formula-editor > summary').click();};
try {
  await page.goto(base+'/editor');
  await page.locator('input[type=file]').first().setInputFiles({name:'mixed-formula-input-copy.svg',mimeType:'image/svg+xml',buffer:Buffer.from(sample)});
  await page.waitForFunction(()=>document.querySelector('.ff-editor-stage')?.dataset.ready==='true'&&!document.querySelector('.product-editor-route-content')?.inert);
  await command('select-layer','txt_unet_label');
  await page.locator('.ff-selection-summary').filter({hasText:'txt_unet_label'}).waitFor();
  await page.locator('.ff-formula-editor > summary').click();
  await page.locator('math-field').waitFor();
  await page.locator('.ff-formula-preview img').waitFor();
  await showSource();
  const converted=await source().inputValue();
  assert.ok(converted.includes(String.raw`\text{\textbf{4. Conditional Denoising U-Net }}`),converted);
  assert.ok(converted.includes(String.raw`\varepsilon_{\theta}`),converted);
  const preview=await page.locator('.ff-formula-preview').evaluate(el=>({width:el.clientWidth,scroll:el.scrollWidth}));
  assert.ok(preview.scroll<=preview.width+1,JSON.stringify(preview));
  checks.push('Actual diffusion title retains text spaces, bold title, epsilon variant and theta subscript; full preview fits the panel');
  await page.getByRole('button',{name:'展开编辑',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  await page.screenshot({path:output+'/mixed-title-expanded.png'});
  await page.getByRole('button',{name:'替换选中对象',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('iframe').contentDocument.getElementById('txt_unet_label')?.hasAttribute('data-figfox-latex'));
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'关闭公式窗口',exact:true}).click();
  await page.getByRole('button',{name:'导出 SVG',exact:true}).click();
  await(await download).saveAs(output+'/edited-title-copy.svg');
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('.ff-editor-stage')?.dataset.ready==='true');
  await command('select-layer','txt_unet_label');
  await showSource();assert.equal(await source().inputValue(),converted);
  checks.push('Mixed text and formula source survives apply, export and reload');
  await select('formula-scripts');await showSource();
  assert.equal(await source().inputValue(),'x^{2}_{i} + y_{j}');
  await select('accent');await showSource();
  assert.equal(await source().inputValue(),String.raw`\text{Noise }\hat{\varepsilon}_{\theta}`);
  checks.push('Consecutive super/subscripts stay on the same variable; later subscripts and combining accents preserve structure');
  await page.getByRole('tab',{name:'可视编辑',exact:true}).click();
  const field=page.locator('math-field');await field.waitFor();
  await field.click();
  await page.waitForFunction(()=>document.activeElement?.tagName==='MATH-FIELD');
  await page.keyboard.press('ControlOrMeta+A');await page.keyboard.press('Backspace');
  await page.keyboard.type(String.raw`\varepsilon`);await page.keyboard.press('Space');
  await page.keyboard.type('_');await page.keyboard.type(String.raw`\theta`);await page.keyboard.press('Space');await page.keyboard.press('ArrowRight');
  await showSource();
  assert.match(await source().inputValue(),/\\varepsilon_\{?\\theta/);
  checks.push('Physical keyboard enters epsilon and theta subscript through LaTeX commands and completion');
  await page.getByRole('tab',{name:'可视编辑',exact:true}).click();await field.waitFor();
  await field.click();await page.waitForFunction(()=>document.activeElement?.tagName==='MATH-FIELD');await page.keyboard.press('ControlOrMeta+A');await page.keyboard.press('Backspace');
  await page.getByRole('button',{name:'普通文字',exact:true}).click();
  await page.waitForFunction(()=>document.activeElement?.tagName==='MATH-FIELD');
  await page.keyboard.type('Conditional Denoising U-Net ');
  await page.getByRole('button',{name:'数学',exact:true}).click();
  await page.waitForFunction(()=>document.activeElement?.tagName==='MATH-FIELD');
  await page.keyboard.type(String.raw`\theta`);await page.keyboard.press('Space');
  await showSource();
  assert.match(await source().inputValue(),/\\text\{Conditional Denoising U-Net /);
  assert.ok((await source().inputValue()).includes(String.raw`\theta`));
  await page.locator('.ff-formula-preview img').waitFor();
  checks.push('Typing ordinary words and switching to math preserves spaces and Greek command input');
  await source().fill(String.raw`\int_0^\infty e^{-x}\,dx = 1\quad\forall x\in\mathbb{R}`);
  await page.locator('.ff-formula-preview img').waitFor();
  assert.equal(await page.locator('.ff-formula-error').count(),0);
  checks.push('Commands beyond preset buttons render: integrals, infinity, quantifiers, set membership and blackboard bold');
  await page.getByRole('tab',{name:'可视编辑',exact:true}).click();await field.waitFor();
  await page.screenshot({path:output+'/visual-input.png'});
  await page.setViewportSize({width:390,height:844});
  await page.locator('.ff-inspector-toggle').click();
  if(!await page.locator('.ff-formula-editor').evaluate(el=>el.open))await page.locator('.ff-formula-editor > summary').click();
  await page.getByRole('button',{name:'展开编辑',exact:true}).click();
  await page.locator('math-field').waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:output+'/visual-mobile.png'});
  await page.locator('math-field [part="virtual-keyboard-toggle"]').click();
  await page.waitForFunction(()=>window.mathVirtualKeyboard.visible);
  assert.equal(await page.evaluate(()=>Boolean(document.querySelector('.ff-formula-dialog .ML__keyboard'))),true);
  await page.locator('.ff-formula-dialog .ML__keyboard').waitFor({state:'visible'});
  await page.waitForFunction(()=>{const r=document.querySelector('.ML__keyboard')?.getBoundingClientRect();return r&&r.height>100&&r.top<innerHeight-100;});
  await page.waitForTimeout(500);
  assert.ok(await page.locator('.ff-formula-dialog .ML__keyboard svg use').count()>0);
  await page.screenshot({path:output+'/symbol-keyboard-mobile.png'});
  await page.locator('.ff-formula-dialog .ML__keyboard [data-keycap-value="7"]').click();
  await page.waitForFunction(()=>document.querySelector('math-field').value.includes('7'));
  await page.evaluate(()=>window.mathVirtualKeyboard.hide());
  assert.ok(requests.some(url=>url.includes('/mathlive-fonts/')));
  assert.equal(requests.some(url=>/cdn\.jsdelivr|unpkg|esm\.run/.test(url)),false);
  checks.push('Mathfield fonts load from this site; narrow expanded editor fits without page overflow');
  assert.deepEqual(errors,[]);
}catch(error){await page.screenshot({path:output+'/failure.png'});throw error;}
finally{await writeFile(output+'/checks.json',JSON.stringify({checks,errors},null,2));await browser.close();}
