import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const base = process.env.AUDIT_BASE_URL || 'http://127.0.0.1:5173';
const output = process.env.AUDIT_OUTPUT || '.review/editor-formula';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
page.setDefaultTimeout(20000);
const checks = [], errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.addInitScript(() => { if (!localStorage.getItem('autodraftman-language')) localStorage.setItem('autodraftman-language', 'en'); });
const frame = page.frameLocator('iframe');
const command = (name, value) => page.evaluate(([name, value]) => document.querySelector('iframe').contentWindow.figfoxCommand(name, value), [name, value]);
const input = page.getByLabel('LaTeX source', { exact: true });
const getFormula = id => frame.locator(`#${id}`).getAttribute('data-figfox-latex');
const waitSource = (id, latex) => page.waitForFunction(([id, latex]) => document.querySelector('iframe').contentDocument.getElementById(id)?.getAttribute('data-figfox-latex') === latex, [id, latex]);
const bounds = id => frame.locator(`#${id}`).evaluate(el => { const b = el.getBBox(); return { x:b.x, y:b.y, width:b.width, height:b.height, transform:el.getAttribute('transform'), parent:el.parentElement.id }; });
const open = async () => { if (!await page.locator('.ff-formula-editor').evaluate(el=>el.open)) await page.locator('.ff-formula-editor summary').click(); };
const render = async latex => { await open(); await input.fill(latex); await page.locator('.ff-formula-preview img').waitFor(); assert.equal(await page.locator('.ff-formula-error').count(), 0); };
const sample = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="500"><g id="module" transform="translate(40 35) scale(1.1)"><text id="equation" x="65" y="110" font-size="32" fill="#6243ce" transform="rotate(12 65 110)">α + β</text><rect id="sibling" x="310" y="70" width="100" height="45" fill="#ddd"/></g></svg>`;
try {
  await writeFile(output + '/input-copy.svg', sample);
  await page.goto(base + '/editor');
  await page.locator('input[type=file]').first().setInputFiles({ name: 'formula-input-copy.svg', mimeType: 'image/svg+xml', buffer: Buffer.from(sample) });
  await page.waitForFunction(() => document.querySelector('.ff-editor-stage')?.dataset.ready === 'true' && !document.querySelector('.product-editor-route-content')?.inert);
  await frame.locator('#equation').waitFor();
  await command('select-layer', 'equation');
  await page.locator('.ff-selection-summary').filter({ hasText: 'equation' }).waitFor();
  const before = await bounds('equation'), sibling = await frame.locator('#sibling').evaluate(el => el.outerHTML);
  const latex = String.raw`\frac{\alpha_t}{\sqrt{1+\beta^2}}`;
  await open(); assert.equal(await input.inputValue(),'α + β');
  await render(latex);
  await page.getByRole('button', { name: 'Replace selection', exact: true }).click();
  await waitSource('equation', latex);
  const after = await bounds('equation');
  assert.equal(after.transform, before.transform); assert.equal(after.parent, before.parent);
  assert.ok(Math.abs(after.x - before.x) < .1 && Math.abs(after.y - before.y) < .1 && Math.abs(after.height - before.height) < .1, JSON.stringify({before,after}));
  assert.equal(await frame.locator('#sibling').evaluate(el => el.outerHTML), sibling);
  assert.equal(await frame.locator('#equation').getAttribute('fill'), 'rgb(98, 67, 206)');
  checks.push('LaTeX replacement preserves position, height, rotation, parent group, color and unrelated objects');
  await command('undo'); await frame.locator('text#equation').waitFor(); assert.equal(await frame.locator('#equation').textContent(), 'α + β');
  await command('redo'); await waitSource('equation', latex);
  checks.push('One undo restores original text; redo restores vector formula and source');
  await command('select-layer', 'equation');
  const updated = String.raw`\sum_{i=1}^{n}\frac{\bar\alpha_i}{\sqrt{1+\beta_i^2}}`;
  await render(updated);
  await page.getByRole('button', { name: 'Apply to formula', exact: true }).click();
  await waitSource('equation', updated);
  const editedBounds = await bounds('equation');
  assert.ok(Math.abs(editedBounds.x-before.x)<.1 && Math.abs(editedBounds.y-before.y)<.1);
  await page.screenshot({ path: output + '/formula-desktop.png' });
  const snapshot = await page.evaluate(() => document.querySelector('iframe').contentWindow.figfoxSnapshot());
  await input.fill(String.raw`\frac{a}{`);
  await page.locator('.ff-formula-error').waitFor();
  assert.equal(await page.getByRole('button',{name:'Apply to formula',exact:true}).isDisabled(),true);
  assert.equal(await page.evaluate(() => document.querySelector('iframe').contentWindow.figfoxSnapshot()),snapshot);
  await input.fill(String.raw`\href{https://example.com}{x}`); await page.locator('.ff-formula-error').waitFor();
  assert.equal(await getFormula('equation'),updated);
  checks.push('Invalid LaTeX and unsupported URL commands cannot modify the canvas');
  await render(updated);
  const download = page.waitForEvent('download'); await page.getByRole('button',{name:'Export SVG',exact:true}).click();
  await (await download).saveAs(output+'/edited-copy.svg');
  const saved = await readFile(output+'/edited-copy.svg','utf8');
  assert.ok(saved.includes('data-figfox-latex')); assert.ok(!saved.includes('<use')); assert.ok(!saved.includes('https://'));
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('.ff-editor-stage')?.dataset.ready==='true');
  await command('select-layer','equation'); await waitSource('equation',updated);
  await input.waitFor(); assert.equal(await input.inputValue(),updated);
  const reopened = await browser.newPage({viewport:{width:1440,height:900}});
  await reopened.addInitScript(()=>{localStorage.clear();localStorage.setItem('autodraftman-language','en');});
  await reopened.goto(base+'/editor');
  await reopened.locator('input[type=file]').first().setInputFiles({name:'reopened-copy.svg',mimeType:'image/svg+xml',buffer:Buffer.from(saved)});
  await reopened.waitForFunction(()=>document.querySelector('.ff-editor-stage')?.dataset.ready==='true'&&!document.querySelector('.product-editor-route-content')?.inert);
  await reopened.frameLocator('iframe').locator('#equation').waitFor();
  await reopened.evaluate(()=>document.querySelector('iframe').contentWindow.figfoxCommand('select-layer','equation'));
  await reopened.getByLabel('LaTeX source',{exact:true}).waitFor();
  assert.equal(await reopened.getByLabel('LaTeX source',{exact:true}).inputValue(),updated);
  await reopened.getByLabel('LaTeX source',{exact:true}).fill(String.raw`E=mc^2`);
  await reopened.locator('.ff-formula-preview img').waitFor();
  await reopened.getByRole('button',{name:'Apply to formula',exact:true}).click();
  await reopened.waitForFunction(()=>document.querySelector('iframe').contentDocument.getElementById('equation')?.getAttribute('data-figfox-latex')==='E=mc^2');
  await reopened.close();
  checks.push('SVG download, session reload and fresh file import retain LaTeX; reopened formula can be edited again');
  await command('deselect');
  const hit = await frame.locator('#equation path').first().boundingBox();
  await page.mouse.click(hit.x + hit.width / 2, hit.y + hit.height / 2);
  await page.getByRole('button',{name:'Apply to formula',exact:true}).waitFor();
  assert.equal(await input.inputValue(),updated);
  checks.push('Clicking a formula glyph selects the formula as one editable object');
  await render(String.raw`\begin{pmatrix} a & b \\ c & d \end{pmatrix}`);
  await page.getByRole('button',{name:'Insert formula',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('iframe').contentDocument.querySelectorAll('#svgcontent [data-figfox-latex]').length===2);
  await command('undo'); await page.waitForFunction(()=>document.querySelector('iframe').contentDocument.querySelectorAll('#svgcontent [data-figfox-latex]').length===1);
  checks.push('Matrix insertion and undo work without replacing the existing formula');
  await page.setViewportSize({width:390,height:844});
  await command('select-layer','equation');
  await page.locator('.ff-inspector-toggle').click();
  await input.waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:output+'/formula-mobile.png'});
  checks.push('Formula controls remain reachable without page overflow on a narrow viewport');
  await page.setViewportSize({width:1440,height:900});
  await page.evaluate(()=>localStorage.setItem('autodraftman-language','zh'));
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('.ff-editor-stage')?.dataset.ready==='true');
  await command('select-layer','equation');
  await page.getByLabel('LaTeX 源码',{exact:true}).waitFor();
  await page.locator('.ff-formula-preview img').waitFor();
  await page.screenshot({path:output+'/formula-zh.png'});
  await page.setViewportSize({width:320,height:640});
  await page.locator('.ff-inspector-toggle').click();
  await page.getByLabel('LaTeX 源码',{exact:true}).waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.getByRole('button',{name:'应用到公式',exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:output+'/formula-zh-mobile.png'});
  checks.push('Chinese formula controls and apply action fit a 320 px viewport');
  assert.deepEqual(errors,[]);
} catch(error) { await page.screenshot({path:output+'/failure.png'}); throw error; }
finally { await writeFile(output+'/checks.json',JSON.stringify({checks,errors},null,2));await browser.close(); }
console.log(JSON.stringify({checks,errors},null,2));
