"""Subset installed Noto for showcase copy, retaining variable weights.
Original Noto remains the fallback for arbitrary evidence/editor text.
Run after changing showcase copy. Requires fonttools[woff].
"""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
font_root = root / 'node_modules/@fontsource-variable/noto-sans-sc'
target = root / 'public/assets/demo/fonts'
target.mkdir(parents=True, exist_ok=True)
paths = list((root / 'src/features/demo').rglob('*.tsx')) + list((root / 'src/features/demo').rglob('*.ts'))
paths += [root / 'public/assets/research/summary.json', root / 'src/SiteEntry.tsx']
text = ''.join(p.read_text('utf-8') for p in paths)
characters = {ord(c) for c in text if ord(c) >= 0x100}
rules, used, total = [], set(), 0
for source in sorted((font_root / 'files').glob('*-wght-normal.woff2')):
    font = TTFont(source, recalcTimestamp=False)
    points = characters.intersection(font.getBestCmap()) - used
    if not points:
        font.close()
        continue
    options = subset.Options()
    options.flavor = 'woff2'
    options.recalc_timestamp = False
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    destination = target / source.name
    font.save(destination)
    font.close()
    used.update(points)
    total += destination.stat().st_size
    ranges = ','.join(f'U+{p:X}' for p in sorted(points))
    rules.append('@font-face{font-family:"FigFox Showcase SC";font-style:normal;font-weight:100 900;font-display:swap;'
                 f'src:url("/assets/demo/fonts/{source.name}") format("woff2");unicode-range:{ranges};}}')
(root / 'src/features/demo/showcase-fonts.css').write_text('/* Generated by prepare-showcase-fonts.py. Noto SIL OFL; see assets/demo/fonts/LICENSE. */\n' + '\n'.join(rules) + '\n', 'utf-8')
(target / 'LICENSE').write_bytes((font_root / 'LICENSE').read_bytes())
assert not {p for p in characters - used if 0x4E00 <= p <= 0x9FFF}, 'Missing CJK characters'
print(f'{len(used)} characters, {len(rules)} subsets, {total:,} bytes; unchanged system fallback: {sorted(characters - used)}')
