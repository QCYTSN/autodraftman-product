// Reuses an existing real result. Makes no model requests or new task submissions.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';

const base = 'http://127.0.0.1:5178';
const output = '.review/local-kernel';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const errors = [], posts = [], checks = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if (r.method() === 'POST') posts.push(r.url()); });
await page.addInitScript(() => {
  localStorage.setItem('autodraftman-language', 'zh');
  addEventListener('message', event => { if (event.data?.source === 'figfox-svgedit' && event.data.type === 'state') window.editorState = event.data.state; });
});
try {
  await page.goto(base + '/workspace', { waitUntil: 'networkidle' });
  const jobs = await (await page.request.get(base + '/local-api/jobs')).json();
  const job = jobs.find(job => job.status === 'succeeded');
  assert.ok(job, 'A previously completed real run is required');
  const result = page.locator('.workspace-reconstruction-result').first();
  await result.waitFor();
  assert.equal(await page.getByRole('dialog').count(), 0);
  const raw = await (await page.request.get(base + job.result.svg)).body();
  assert.equal(createHash('sha256').update(raw).digest('hex'), job.result.sha256);
  checks.push('Refresh restores the real result; raw SVG matches the kernel hash');
  await page.getByRole('button', { name: '查看进度', exact: true }).click();
  await page.waitForTimeout(400);
  await page.screenshot({ path: output + '/05-completed-progress.png' });
  await page.getByRole('button', { name: '关闭进度', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'detached' });
  for (const name of ['SVG', 'PNG']) {
    const download = page.waitForEvent('download');
    await result.getByRole('link', { name, exact: true }).click();
    await (await download).saveAs(`${output}/downloaded-result.${name.toLowerCase()}`);
  }
  assert.equal(createHash('sha256').update(await readFile(output + '/downloaded-result.svg')).digest('hex'), job.result.sha256);
  checks.push('Both downloads work; SVG download preserves the original generated bytes');
  await result.getByRole('button', { name: '打开 SVG 编辑', exact: true }).click();
  await page.waitForURL(/\/editor/);
  const ready = () => page.waitForFunction(() => document.querySelector('.ff-editor-stage')?.dataset.ready === 'true' && !document.querySelector('.product-editor-route-content')?.inert);
  await ready();
  const target = await page.frameLocator('iframe').locator('#svgcontent text').first().getAttribute('id');
  assert.ok(target);
  await page.evaluate(id => document.querySelector('iframe').contentWindow.figfoxCommand('select-layer', id), target);
  await page.waitForFunction(id => window.editorState?.selection?.id === id, target);
  const content = page.getByRole('textbox', { name: '文字内容', exact: true });
  await content.fill('Editable FigFox');
  await content.press('Tab');
  await page.waitForFunction(id => document.querySelector('iframe').contentDocument.getElementById(id)?.textContent === 'Editable FigFox', target);
  await page.waitForTimeout(1200);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 SVG', exact: true }).click();
  await (await download).saveAs(output + '/edited-in-browser.svg');
  assert.ok((await readFile(output + '/edited-in-browser.svg', 'utf8')).includes('Editable FigFox'));
  await page.goto(base + '/workspace', { waitUntil: 'networkidle' });
  await result.getByRole('button', { name: '打开 SVG 编辑', exact: true }).click();
  await ready();
  await page.waitForFunction(id => document.querySelector('iframe').contentDocument.getElementById(id)?.textContent === 'Editable FigFox', target);
  checks.push('Generated text is editable and exportable; reopening the result preserves saved edits');
  await page.goto(base + '/workspace', { waitUntil: 'networkidle' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '查看进度', exact: true }).click();
  await page.waitForTimeout(400);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.ok(await page.getByRole('dialog').getByRole('button', { name: '打开 SVG 编辑', exact: true }).isVisible());
  await page.screenshot({ path: output + '/06-result-mobile.png' });
  checks.push('Real result and controls fit the mobile progress dialog');
  const publicPage = await browser.newPage();
  const localRequests = [];
  publicPage.on('request', request => { if (request.url().includes('/local-api/') || request.url().includes(':8787/')) localRequests.push(request.url()); });
  await publicPage.goto((process.env.AUDIT_STATIC_URL || 'http://127.0.0.1:4176/figfox') + '/workspace', { waitUntil: 'networkidle' });
  assert.equal(await publicPage.locator('.generate-button').isDisabled(), true);
  assert.deepEqual(localRequests, []);
  await publicPage.close();
  checks.push('Production build makes no local service requests and does not enable generation');
  assert.equal(errors.length, 0, errors.join('\n'));
  assert.equal(posts.length, 0, 'Result review must never submit a new paid job');
  console.log(JSON.stringify({ checks, errors, posts }));
} finally {
  await writeFile(output + '/result-checks.json', JSON.stringify({ checks, errors, posts }, null, 2));
  await browser.close();
}
