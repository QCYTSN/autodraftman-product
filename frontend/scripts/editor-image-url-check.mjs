import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const base = process.env.AUDIT_BASE_URL || 'http://127.0.0.1:5173';
const output = process.env.AUDIT_OUTPUT || '.review/editor-layout';
await mkdir(output,{recursive:true});
const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page = await browser.newPage({viewport:{width:1440,height:900},acceptDownloads:true});
const checks=[],errors=[];
page.on('pageerror',error=>errors.push(error.message));
await page.addInitScript(()=>localStorage.setItem('autodraftman-language','en'));
const frame=page.frameLocator('iframe');
const replace=async()=>{
 await page.evaluate(()=>document.querySelector('iframe').contentWindow.figfoxCommand('select-layer','test-image'));
 await page.getByRole('button',{name:'Replace image source',exact:true}).click();
};
const href=()=>frame.locator('#test-image').evaluate(el=>el.getAttribute('href')||el.getAttribute('xlink:href'));
try {
 await page.goto(base+'/editor');
 const images=await page.evaluate(()=>['#6243ce','#24a37a'].map(color=>{const canvas=document.createElement('canvas');canvas.width=canvas.height=16;const ctx=canvas.getContext('2d');ctx.fillStyle=color;ctx.fillRect(0,0,16,16);return canvas.toDataURL();}));
 await page.route('**/layout-image.png',route=>route.fulfill({status:200,contentType:'image/png',body:Buffer.from(images[1].split(',')[1],'base64')}));
 const sample=`<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600"><image id="test-image" href="${images[0]}" x="100" y="100" width="180" height="120"/></svg>`;
 await page.locator('input[type=file]').first().setInputFiles({name:'image-url-input-copy.svg',mimeType:'image/svg+xml',buffer:Buffer.from(sample)});
 await page.waitForFunction(()=>document.querySelector('.ff-editor-stage')?.dataset.ready==='true' && !document.querySelector('.product-editor-route-content')?.inert);
 await replace();
 await page.getByLabel('Or use an image URL',{exact:true}).fill(base+'/layout-image.png');
 await page.getByRole('dialog').getByRole('button',{name:'Replace image',exact:true}).click();
 await page.getByRole('dialog').waitFor({state:'detached'});
 await page.waitForFunction(expected=>{const image=document.querySelector('iframe').contentDocument.getElementById('test-image');return (image.getAttribute('href')||image.getAttribute('xlink:href'))===expected;},images[1]);
 assert.equal(await frame.locator('#test-image').getAttribute('width'),'180');
 await page.getByRole('button',{name:'Undo',exact:true}).click();
 await page.waitForTimeout(100);
 assert.equal(await href(),images[0]);
 await page.getByRole('button',{name:'Redo',exact:true}).click();
 await page.waitForTimeout(100);
 assert.equal(await href(),images[1]);
 const pending=page.waitForEvent('download');
 await page.getByRole('button',{name:'Export SVG',exact:true}).click();
 await (await pending).saveAs(output+'/image-url-edited-copy.svg');
 const saved=await readFile(output+'/image-url-edited-copy.svg','utf8');
 assert.ok(saved.includes(images[1]));
 assert.ok(!saved.includes('/layout-image.png'));
 checks.push('Image URL reads a real PNG and embeds it; replacement retains dimensions and the downloaded SVG contains the image bytes');
 await page.route('**/layout-denied.png',route=>route.abort('accessdenied'));
 await replace();
 await page.getByLabel('Or use an image URL',{exact:true}).fill(base+'/layout-denied.png');
 await page.getByRole('dialog').getByRole('button',{name:'Replace image',exact:true}).click();
 await page.locator('.ff-image-dialog-error').waitFor();
 assert.match(await page.locator('.ff-image-dialog-error').innerText(),/Could not read/);
 assert.equal(await href(),images[1]);
 await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
 checks.push('Unavailable URL explains recovery and leaves the existing image unchanged');
 let requested=false,failed=false,release;
 const gate=new Promise(resolve=>release=resolve);
 page.on('requestfailed',request=>{if(request.url().endsWith('/layout-cancel.png'))failed=true;});
 await page.route('**/layout-cancel.png',async route=>{requested=true;await gate;await route.abort().catch(()=>{});});
 await replace();
 await page.getByLabel('Or use an image URL',{exact:true}).fill(base+'/layout-cancel.png');
 await page.getByRole('dialog').getByRole('button',{name:'Replace image',exact:true}).click();
 const started=Date.now();while(!requested&&Date.now()-started<5000)await new Promise(resolve=>setTimeout(resolve,20));
 assert.equal(requested,true);
 await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
 await page.waitForTimeout(100);
 assert.equal(await href(),images[1]);
 release();
 await page.waitForTimeout(100);
 assert.equal(failed,true);
 checks.push('Cancel aborts a pending image request without replacing the current image');
 assert.deepEqual(errors,[]);
} finally { await writeFile(output+'/image-url-checks.json',JSON.stringify({checks,errors},null,2));await browser.close(); }
console.log(JSON.stringify({checks,errors},null,2));
