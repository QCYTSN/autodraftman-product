import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, mkdir, writeFile } from 'node:fs/promises';

const base = (process.env.AUDIT_BASE_URL || 'http://127.0.0.1:4175/figfox').replace(/\/$/, '');
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const checks = [], requests = [], errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
  await page.addInitScript(() => localStorage.setItem('autodraftman-language', 'zh'));
  page.on('request', r => requests.push(new URL(r.url()).pathname));
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base + '/', { waitUntil: 'networkidle' });
  await page.evaluate(() => document.fonts.ready);
  assert.equal(requests.filter(u => u.endsWith('/summary.json')).length, 1);
  assert.equal(requests.some(u => /\/(samples|pipeline)\.json|\/sample-meta\/|\/details\//.test(u)), false);
  assert.equal(requests.some(u => /\/cases\/.+\/(input\.png|result\.png|result\.svg)|crop-(draft|original)\.png|figfox-method-20261103\.png/.test(u)), false);
  assert.equal(requests.some(u => /\/App-.*\.(js|css)/.test(u)), false);
  const thumbs = await page.locator('.demo-case-picker img').evaluateAll(es => es.map(e => ({src:e.src, lazy:e.loading, decoding:e.decoding, w:e.width,h:e.height})));
  assert.equal(thumbs.length, 4);
  assert.ok(thumbs.every(t => t.src.endsWith('/thumbnail.webp') && t.lazy === 'lazy' && t.decoding === 'async' && t.w > 0 && t.h > 0));
  checks.push('Cold desktop: one summary, dedicated thumbnails, no original PNGs, hidden modal crops, sample index or product bundle');
  await page.locator('#demo-benchmarks').scrollIntoViewIfNeeded();
  assert.equal(requests.some(u => /\/(samples)\.json|\/sample-meta\/|\/details\//.test(u)), false);
  await page.locator('.research-profiles button').first().click();
  await page.locator('.research-dialog [data-sample]').waitFor();
  assert.equal(await page.locator('.research-output-grid article').count(), 4);
  assert.equal(requests.filter(u => u.endsWith('/samples.json')).length, 1);
  assert.equal(requests.filter(u => u.includes('/sample-meta/')).length, 1);
  assert.equal(requests.some(u => u.includes('/details/')), false);
  const sample = page.getByRole('combobox', { name: '样本', exact: true });
  for (const sid of ['sample-0033','sample-0097']) {
    await sample.selectOption(sid);
    await page.locator(`[data-sample="${sid}"]`).waitFor();
    const image = page.locator('[data-method="AFE"] .research-output img');
    await image.evaluate(e => e.decode());
    assert.ok(await image.evaluate(e => e.naturalWidth > 0 && getComputedStyle(e).objectFit === 'contain'));
    assert.ok(new URL(await image.getAttribute('src'), base).pathname.endsWith(sid + '/AFE.webp'));
  }
  await sample.selectOption('sample-0062');
  await page.locator('[data-sample="sample-0062"]').waitFor();
  const afe = page.locator('.research-output-grid [data-method="AFE"]');
  assert.match(await afe.innerText(), /原始 SVG 损坏/);
  const dl = page.waitForEvent('download');
  await afe.getByRole('link', {name:/下载损坏原件/}).click();
  const download = await dl;
  const bytes = await readFile(await download.path());
  const metadata = await (await page.request.get(base + '/assets/research/sample-meta/sample-0062.json')).json();
  assert.equal(createHash('sha256').update(bytes).digest('hex'), metadata.artifacts.AFE.svgHash);
  await sample.selectOption('sample-0030');
  await page.locator('[data-sample="sample-0030"]').waitFor();
  await page.locator('[data-method="AFE"] .research-output img').evaluate(e => e.decode());
  checks.push('AutoFigure previews 0033/0097 and original-SVG rendering 0030; damaged 0062 downloads with the exact original hash');

  // A slow unseen response must never overwrite the final selection.
  await page.route('**/sample-meta/sample-0002.json*', async route => {
    await new Promise(r => setTimeout(r, 650));
    await route.continue().catch(() => {});
  });
  await sample.selectOption('sample-0002');
  await page.waitForTimeout(200);
  assert.equal(await page.locator('.research-dialog [data-sample]').count(), 0);
  await sample.selectOption('sample-0003');
  await sample.selectOption('sample-0097');
  await page.locator('[data-sample="sample-0097"]').waitFor();
  await page.waitForTimeout(750);
  assert.equal(await page.locator('.research-dialog [data-sample]').getAttribute('data-sample'), 'sample-0097');
  assert.equal(requests.filter(u => u.endsWith('/sample-meta/sample-0097.json')).length, 1);
  assert.equal(requests.some(u => u.endsWith('/sample-meta/sample-0003.json')), false);
  assert.equal(requests.some(u => u.includes('/details/')), false);
  const evidenceResponse = page.waitForResponse(r => new URL(r.url()).pathname.endsWith('/details/sample-0097.json'));
  await page.locator('.research-output-grid details summary').first().click();
  await evidenceResponse;
  await page.locator('.research-output-grid details p b').first().waitFor();
  assert.equal(requests.filter(u => u.includes('/details/')).length, 1);
  checks.push('Rapid switches coalesce, abort stale metadata, remove old images/scores, and reuse the selected sample cache; evidence loads only when expanded');
  await page.getByRole('button',{name:'关闭比较',exact:true}).click();
  await page.locator('.research-dialog').waitFor({state:'detached'});
  const before = await page.evaluate(() => scrollY);
  await page.locator('.research-profiles button').first().click();
  await page.locator('.research-dialog [data-sample]').waitFor();
  await page.getByRole('button',{name:'关闭比较',exact:true}).click();
  await page.waitForTimeout(100);
  assert.ok(Math.abs(await page.evaluate(() => scrollY) - before) < 2);
  assert.equal(requests.filter(u => u.endsWith('/summary.json')).length, 1);
  assert.equal(requests.filter(u => u.endsWith('/samples.json')).length, 1);
  assert.ok(requests.filter(u => /\/samples\/.+\.svg$/.test(u)).every(u => u.endsWith('/sample-0062/AFE.svg')), 'No SVGs are prefetched; the explicitly downloaded damaged original is checked above');
  checks.push('Close restores scroll position; repeat opens reuse summary/index, and originals load only on download');
  await page.locator('.demo-header').getByRole('link',{name:'开始使用'}).click();
  await page.locator('#figure-prompt').waitFor();
  await page.goBack();
  await page.locator('.demo-hero').waitFor();
  await page.goto(base+'/?auth_error=authorization_cancelled',{waitUntil:'networkidle'});
  await page.waitForURL(/\/login$/);
  assert.equal(new URL(page.url()).search, '');
  checks.push('Deferred product navigation, browser Back and existing auth callback routing are preserved');
  assert.deepEqual(errors, []);
  await mkdir('.review/research', {recursive:true});
  await writeFile('.review/research/loading-checks.json', JSON.stringify({checks,errors,requests},null,2));
  console.log(JSON.stringify({checks,errors},null,2));
} finally { await browser.close(); }
