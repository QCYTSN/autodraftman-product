import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const active = JSON.parse(await readFile(path.join(root, 'public/assets/presentation/active-case.json'), 'utf8'));
assert(/^sample-\d{4}$/.test(active.id));
const folder = path.join(root, 'public/assets/presentation', active.id);
const generated = path.join(root, 'src/features/presentation/data');
const manifest = JSON.parse(await readFile(path.join(folder, 'manifest.json'), 'utf8'));
assert.equal(manifest.id, active.id);
assert(manifest.issues.length > 0 && manifest.repair.operations.length > 0);
const media = {};
const report = [];
for (const [name, hash] of Object.entries(manifest.provenance.bundledHashes)) {
  assert.equal(path.basename(name), name);
  const data = await readFile(path.join(folder, name));
  assert.equal(createHash('sha256').update(data).digest('hex'), hash, 'Changed case resource: ' + name);
  const svg = name.endsWith('.svg');
  const value = data.toString('utf8');
  if (svg) {
    assert(!/<script|<foreignObject|\son\w+=|(?:href|src)=["']https?:/i.test(value), 'Active or remote SVG: ' + name);
    assert(value.includes('viewBox="' + manifest.dimensions.viewBox.join(' ') + '"'));
  }
  media[name] = svg ? value : 'data:image/' + (name.endsWith('.png') ? 'png' : 'webp') + ';base64,' + data.toString('base64');
  report.push({ name, bytes: data.length, sha256: hash });
}
const regions = [...manifest.issues.flatMap(issue => ['sourceRegion', 'draftRegion', 'finalRegion'].map(key => issue[key])), ...(manifest.issueMap ?? []).map(issue => issue.region)];
for (const region of regions) {
  const { box: [l, t, r, b], coordinateWidth: w, coordinateHeight: h } = region;
  assert(l >= 0 && t >= 0 && r > l && b > t && r <= w && b <= h);
}
if (manifest.repair.unresolvedItems) assert.equal(manifest.repair.unresolvedCount, manifest.repair.unresolvedItems.length);
if (manifest.issueMap) {
  assert.equal(new Set(manifest.issueMap.map(issue => issue.id)).size, manifest.issueMap.length);
  assert(manifest.issueMap.some(issue => issue.id === manifest.issues[0].id));
}
assert(media[manifest.svg.final].includes('id="' + manifest.editTarget.elementId + '"'));
const logo = await readFile(path.join(root, 'public/assets/demo/figfox-logo.svg'));
media.logo = 'data:image/svg+xml;base64,' + logo.toString('base64');
const font = await readFile(path.join(root, 'node_modules/@fontsource-variable/figtree/files/figtree-latin-wght-normal.woff2'));
await mkdir(generated, { recursive: true });
await copyFile(path.join(folder, 'manifest.json'), path.join(generated, 'case-manifest.json'));
// Generated module shared by the online lazy chunk and the standalone bundle.
await writeFile(path.join(generated, 'prepared-case.ts'), '// Generated by presentation:prepare. Do not edit.\nimport type { PresentationCase } from "../types";\nexport const presentationCase: PresentationCase = ' + JSON.stringify(manifest) + ';\nexport const media: Record<string, string> = ' + JSON.stringify(media).replaceAll('<', '\\u003c').replaceAll('\u2028', '\\u2028').replaceAll('\u2029', '\\u2029') + ';\n');
await writeFile(path.join(generated, 'prepared-font.ts'), 'export const fontData = "data:font/woff2;base64,' + font.toString('base64') + '";\n');
await writeFile(path.join(folder, 'resource-report.json'), JSON.stringify({ files: report, checked: true }, null, 2) + '\n');
console.log('Presentation: verified ' + report.length + ' resources; ' + manifest.repair.kind + '; ' + manifest.sam.mode);
